    private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImprimirActionPerformed
     if (vector == null) {
    JOptionPane.showMessageDialog(this, "Primero crea el vector");
    return;
}

if (posicion < vector.getTamaño()) {
    JOptionPane.showMessageDialog(this, "Todavía faltan valores por ingresar");
    return;
}

modelo1.clear();

for (int i = 0; i < vector.getTamaño(); i++) {
    modelo1.addElement(String.valueOf(vector.getVector()[i]));
}

     // TODO add your handling code here:
    }//GEN-LAST:event_btnImprimirActionPerformed

    private void btnOrdenarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOrdenarActionPerformed
if (vector == null) {
    JOptionPane.showMessageDialog(this, "Primero crea el vector");
    return;
}

if (posicion < vector.getTamaño()) {
    JOptionPane.showMessageDialog(this, "Primero termina de llenar el vector");
    return;
}

vector.ordenar();

modelo2.clear();

for (int i = 0; i < vector.getTamaño(); i++) {
    modelo2.addElement(String.valueOf(vector.getVector()[i]));
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnOrdenarActionPerformed

