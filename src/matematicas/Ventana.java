    private void btnSiguienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSiguienteActionPerformed
           if (vector == null) {

    try {
        int tamaño = Integer.parseInt(txtTamaño.getText());

        if (tamaño <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un tamaño válido");
            return;
        }

        vector = new Vectores(tamaño);
        posicion = 0;

        lblPosicion.setText("0");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Ingrese un tamaño válido");
    }

} else {

    if (posicion < vector.getTamaño()) {

        try {
            int numero = Integer.parseInt(txtValor.getText());

            vector.agregar(numero, posicion);

            posicion++;

            txtValor.setText("");
            lblPosicion.setText(String.valueOf(posicion));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un número entero");
        }

    } else {
        JOptionPane.showMessageDialog(this,
                "El vector está lleno");
    }
}
           for (int i = 0; i < vector.getTamaño();  i++){
               if(i==posicion){
                   lblPosicion.setText(String.valueOf(i+1));
               }
           }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnSiguienteActionPerformed

